#!/usr/bin/env python3
"""Extract fixed-entry Act 3 boss (QUEEN) specs for BossLab, in the Act 2 spec shape.

Reads only main-tree run artifacts (gitignored) and writes specs next to this script. The output
keeps the field names `.dsh/extract_boss_specs.py` used for Act 2 so `make_bosslab_plan.py` works
unchanged, and adds what the Act 3 harness needs:

  piles[].enchantment / piles[].enchantment_amount   CardModel.FromSerializable restores these
                                                     (CardModel.cs:2216-2240), so an enchantment is
                                                     no longer a reason to drop a spec.
  entry_powers_expected_from_relics                  powers the injected relic list produces by
                                                     itself on room entry (do NOT inject these too)
  entry_powers_residual                              per-power amounts to inject: recorded entry
                                                     amount minus the relic-expected amount
  entry_mid_turn, card_value_state, relic_run_state, unresolved
                                                     fidelity notes and the real drop reasons

`unresolved` here means only what BossLab still cannot reproduce:
  relic counters are now restored when the trace carried the relic_counters column (BossLab writes
  them back at the first decision); only a counter relic on a spec from a bridge that predates that
  column is unresolved, because there the counter is unknowable, card values a run changed through a
  relic's own props/counters, a relic whose entry grant depends on invisible run state (Ember Tea,
  Girya), and an entry observation taken after the fight had already started (played-card counters
  are not restorable).

Usage: python3 .dsh/extract_act3_specs.py [--traces-dir DIR] [--out-dir DIR]
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path("/Users/mao/.sts2/wt-bosslab/.dsh")
REPO = HERE.parent  # worktree root
sys.path.insert(0, str(HERE))
import act3_entry_powers as entry_lib  # noqa: E402  curated relic-entry-grant table
sys.path.insert(0, str(REPO / "bosslab" / "tools"))
from relic_entry_effects import restorable_counter_relics  # noqa: E402  the restorable counter relics

MAIN_TREE = Path("/Users/mao/workspace/sts2-ai")
ENTER = re.compile(
    r"^\d\d:\d\d:\d\d\.\d+ \[INFO\] \[AutoSlay\] Entering (\w+) room \(Act (\d+), Floor (\d+)\)"
)
SEED_LINE = re.compile(r"\[AutoSlay\] Starting run with seed=([A-Z0-9]+)")
COMBAT_KINDS = ("Monster", "Elite", "Boss")
BOSS_MONSTER = None
ENCOUNTER_HINT = "ENCOUNTER.THE_INSATIABLE_BOSS"
ACT_INDEX = 1
PILE_KEYS = ("hand", "draw_pile", "discard_pile", "exhaust_pile")
COMPUTED_VARS = entry_lib.__dict__.get("COMPUTED_VARS", {
    "CalculatedEnergy", "CalculatedBlock", "CalculatedDamage", "CalculationBase", "CalculationExtra"})
# Per-enchantment amounts as the game's own sources apply them. The trace shows only the enchantment
# id, so the amount has to come from the source; the real-machine check confirms it card by card.
ENCHANTMENT_AMOUNTS = {
    "ENCHANTMENT.TEZCATARAS_EMBER": 1,   # NutritiousSoup.cs:26-28 CardCmd.Enchant<TezcatarasEmber>(item, 1m)
    "ENCHANTMENT.NIMBLE": 2,             # FresnelLens.cs:19 CanonicalVars NimbleAmount 2
    "ENCHANTMENT.CORRUPTED": 1,          # Symbiote.cs:54 amount: 1
    "ENCHANTMENT.SOULS_POWER": 1,        # GraveOfTheForgotten.cs:54 amount 1
    "ENCHANTMENT.GOOPY": 1,              # PaelsClaw.cs:37-39 CardCmd.Enchant<Goopy>(item, 1m)
    "ENCHANTMENT.VIGOROUS": 8,           # StoneOfAllTime.cs:44-110 PushVigorousAmount 8
}
# Relics whose entry-time effect reads run state the trace never shows (their own [SavedProperty],
# the used-up flag derived from it, or the run's room position). BossLab creates relics fresh, so the
# lab's copy fires where the recorded run had already spent it, or stays silent where the recorded run
# still had state queued. Generated by .dsh/scan_relic_run_state.py from the decompiled sources; the
# fallback keeps this script usable if the scan has not been run.
RUN_STATE_RELIC_SOURCE = Path(__file__).resolve().parent / "relic_run_state.json"
RUN_STATE_RELICS_FALLBACK = {
    "RELIC.EMBER_TEA": "EmberTea.cs guard `!IsUsedUp` (CombatsLeft)",
    "RELIC.GIRYA": "Girya.cs amount = TimesLifted",
    "RELIC.TEA_OF_DISCOURTESY": "TeaOfDiscourtesy.cs BeforeCombatStart, CombatsLeft-gated 2 Dazed",
    "RELIC.VENERABLE_TEA_SET": "VenerableTeaSet.cs GainEnergyInNextCombat queued in the room hook",
    "RELIC.STONE_CALENDAR": "Act 2 exclusion (run-position dependent)",
}


def load_run_state_relics() -> dict[str, str]:
    if not RUN_STATE_RELIC_SOURCE.is_file():
        return dict(RUN_STATE_RELICS_FALLBACK)
    payload = json.loads(RUN_STATE_RELIC_SOURCE.read_text(encoding="utf-8"))
    out = {}
    for relic, info in (payload.get("entry_state_relics") or {}).items():
        out[relic] = (f"{info['evidence']} saved prop {','.join(info['saved_props'])} read in "
                      f"{','.join(h for h in info['hooks'])}")
    for relic, reason in RUN_STATE_RELICS_FALLBACK.items():
        out.setdefault(relic, reason)
    return out


RUN_STATE_RELICS = load_run_state_relics()
RELIC_GRANTS = entry_lib.load_relic_map()


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return ""


def rows_of(path: Path) -> list[dict]:
    out = []
    for line in read_text(path).splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except ValueError:
            continue
        if isinstance(record, dict):
            out.append(record)
    return out


def room_entries(text: str) -> list[tuple[str, int, int]]:
    rooms: list[tuple[str, int, int]] = []
    previous = None
    for line in text.splitlines():
        match = ENTER.match(line)
        if not match:
            continue
        item = (match.group(1), int(match.group(2)), int(match.group(3)))
        if item == previous:
            continue
        previous = item
        rooms.append(item)
    return rooms


def combat_blocks(rows: list[dict]) -> list[dict]:
    blocks: list[dict] = []
    current = None
    for row in rows:
        if row.get("phase") == "combat":
            if current is None:
                current = {"lines": [row]}
                blocks.append(current)
            else:
                current["lines"].append(row)
        elif row.get("phase") == "combat_end" and current is not None:
            current["end"] = row
            current = None
    return blocks


def card_view(card: dict | None) -> dict | None:
    if not isinstance(card, dict) or not card.get("id"):
        return None
    enchantment = card.get("enchantment") or ""
    grown: list[dict] = []
    for var in card.get("vars") or ():
        if not isinstance(var, dict):
            continue
        base, value = var.get("base_value"), var.get("value")
        if base is None or value is None or value == base or var.get("id") in COMPUTED_VARS:
            continue
        grown.append({"var": var.get("id"), "base": base, "value": value})
    return {
        "id": card["id"],
        "upgrade": int(card.get("upgrade") or 0),
        "enchantment": enchantment,
        "enchantment_amount": ENCHANTMENT_AMOUNTS.get(enchantment, 1) if enchantment else 0,
        "grown": grown,
    }


def piles_of(entry: dict) -> dict[str, list[dict]]:
    piles = {}
    for key in PILE_KEYS:
        piles[key] = [card for card in (card_view(item) for item in (entry.get(key) or ())) if card]
    return piles


def deck_multiset(piles: dict[str, list[dict]]) -> list[str]:
    return sorted(f"{card['id']}+{card['upgrade']}+{card['enchantment'] or '-'}"
                  for pile in piles.values() for card in pile)


def spec_id_of(key: tuple) -> str:
    return hashlib.sha256(json.dumps(key, sort_keys=True).encode("utf-8")).hexdigest()[:12]


def powers_of(snapshot: dict | None) -> dict[str, int]:
    out = {}
    for power in (snapshot or {}).get("powers") or ():
        if isinstance(power, dict) and power.get("id"):
            out[str(power["id"]).split(".")[-1]] = int(power.get("amount") or 0)
    return out


def expected_relic_powers(relics: list[str]) -> dict[str, int]:
    """What the injected relic list produces on its own when the boss room is entered."""
    expected: collections.Counter = collections.Counter()
    for relic in relics:
        info = RELIC_GRANTS.get(relic)
        if not info:
            continue
        for grant in info["grants"]:
            if grant.get("state_dependent") or grant.get("carries_in"):
                continue
            if grant.get("amount") is None:
                continue
            expected[grant["power"]] += int(grant["amount"])
    return dict(expected)


def unexplained_card_values(piles: dict[str, list[dict]], powers: dict[str, int]) -> list[dict]:
    """Card values a run changed that neither entry buffs nor the card's own enchantment explains."""
    buff = int(powers.get("STRENGTH_POWER") or 0) + int(powers.get("VIGOR_POWER") or 0)
    out = []
    for pile, cards in piles.items():
        for card in cards:
            for mark in card["grown"]:
                if card["enchantment"]:
                    continue
                delta = mark["value"] - mark["base"]
                if mark["var"] in ("Damage", "Block") and abs(delta) <= max(buff, 0):
                    continue
                out.append({"pile": pile, "card": card["id"], **mark})
    return out


def build_spec(trace: Path, entry: dict, end: dict | None, rooms: list[tuple[str, int, int]],
               index: int, run_seed: str | None) -> dict:
    piles = piles_of(entry)
    player = entry.get("player") or {}
    powers = powers_of(player)
    expected = expected_relic_powers(list(player.get("relics") or ()))
    residual: dict[str, int] = {}
    for name, amount in powers.items():
        remaining = amount - expected.get(name, 0)
        if remaining > 0:
            residual[name] = remaining
    over: dict[str, int] = {}
    for name, amount in expected.items():
        remaining = amount - powers.get(name, 0)
        if remaining > 0:
            over[name] = remaining

    kind, act, floor = rooms[index]
    per_act: collections.Counter = collections.Counter()
    for prior_index, (prior_kind, prior_act, prior_floor) in enumerate(rooms):
        if prior_index == index:
            continue
        per_act[prior_act - 1] += 1
    max_act = max(per_act, default=act - 1)
    history_per_act = [per_act.get(i, 0) for i in range(0, max_act + 1)]

    plays = entry.get("plays") or {}
    mid_turn = int(plays.get("cards_this_turn") or 0) > 0
    values = unexplained_card_values(piles, powers)
    run_state_relics = sorted(set(player.get("relics") or ()) & set(RUN_STATE_RELICS))
    # A trace from a bridge that emitted the relic_counters column carries it even when empty (a player
    # with no counter relic); an older bridge omitted the key entirely, so its counters are unknowable.
    relic_counters_observed = "relic_counters" in player

    unresolved: list[str] = []
    if restorable_counter_relics(player.get("relics") or ()) and not relic_counters_observed:
        unresolved.append("relic_counters_unobserved")
    if values:
        unresolved.append("card_value_state")
    if run_state_relics:
        unresolved.append("relic_run_state:" + ",".join(R for R in run_state_relics))
    if mid_turn:
        unresolved.append("entry_mid_turn")
    if over:
        unresolved.append("relic_overapplies:" + ",".join(f"{k}+{v}" for k, v in sorted(over.items())))

    enemies = []
    for enemy in entry.get("enemies") or ():
        if not isinstance(enemy, dict) or not enemy.get("id"):
            continue
        enemies.append({
            "id": enemy["id"], "hp": enemy.get("hp"), "max_hp": enemy.get("max_hp"),
            "slot": enemy.get("slot"), "move": enemy.get("move"),
            "history": list(enemy.get("history") or ()),
            "intents": list(enemy.get("intents") or ()),
            "powers": list(enemy.get("powers") or ()),
        })
    key = (run_seed, act, floor, player.get("hp"), player.get("max_hp"),
           tuple(deck_multiset(piles)), tuple(player.get("relics") or ()),
           tuple(sorted((str(k), str(v)) for k, v in (player.get("relic_counters") or {}).items())),
           tuple(entry.get("potions") or ()), tuple((e["id"], e["hp"]) for e in enemies))
    tag = trace.name[: -len("_agent.jsonl")].rpartition("_")[0]
    seed_in_name = trace.name[: -len("_agent.jsonl")].rpartition("_")[2]
    return {
        "spec_id": spec_id_of(key),
        "encounter_hint": "+".join(sorted(str(e.get("id")) for e in entry.get("enemies") or ())),
        "run_seed": run_seed,
        "act_index": ACT_INDEX,
        "act_floor": floor,
        "total_floor_including_boss": index + 1,
        "history_per_act": history_per_act,
        "room_type": kind,
        "character": "CHARACTER.IRONCLAD",
        "unresolved": unresolved,
        "entry_powers_observed": powers,
        "entry_powers_expected_from_relics": expected,
        "entry_powers_residual": [{"id": f"POWER.{name}", "amount": amount}
                                  for name, amount in sorted(residual.items())],
        "entry_powers_overapplied": over,
        "entry_mid_turn": mid_turn,
        "entry_mid_turn_cards_this_turn": int(plays.get("cards_this_turn") or 0),
        "card_value_state": values,
        "relic_run_state": run_state_relics,
        "relic_counters_observed": relic_counters_observed,
        "player": {
            "hp": player.get("hp"), "max_hp": player.get("max_hp"), "block": player.get("block"),
            "energy": player.get("energy"), "max_energy": player.get("max_energy"),
            "relics": list(player.get("relics") or ()),
            "relic_counters": dict(player.get("relic_counters") or {}),
            "powers": [{"id": f"POWER.{name}", "amount": amount}
                       for name, amount in sorted(powers.items())],
        },
        "potions": [item.get("id") if isinstance(item, dict) else item
                    for item in (entry.get("potions") or ())],
        "piles": piles,
        "deck_size": sum(len(pile) for pile in piles.values()),
        "enemies": enemies,
        "recorded_outcome": {"won": (end or {}).get("won"), "end_hp": (end or {}).get("hp")},
        "sources": [{"trace": trace.name, "tag": tag, "seed": seed_in_name,
                     "entry_seq": entry.get("seq")}],
    }


def collect(traces_dir: Path) -> tuple[list[dict], collections.Counter]:
    specs: dict[str, dict] = {}
    stats: collections.Counter = collections.Counter()
    for trace in sorted(traces_dir.glob("*_agent.jsonl")):
        modlog = trace.with_name(trace.name[: -len("_agent.jsonl")] + "_mod.log")
        if not modlog.is_file():
            stats["no_modlog"] += 1
            continue
        text = read_text(modlog)
        if f"Entering Boss room (Act {ACT_INDEX + 1}, Floor" not in text:
            stats["no_act3_boss"] += 1
            continue
        rooms = room_entries(text)
        if not any(kind == "Boss" and act == ACT_INDEX + 1 for kind, act, _floor in rooms):
            stats["no_act3_boss"] += 1
            continue
        rows = rows_of(trace)
        blocks = combat_blocks(rows)
        combat_rooms = [(i, room) for i, room in enumerate(rooms) if room[0] in COMBAT_KINDS]
        if len(combat_rooms) != len(blocks):
            stats["unaligned"] += 1
            continue
        seed_match = SEED_LINE.search(text)
        run_seed = seed_match.group(1) if seed_match else None
        for pair_index, (index, room) in enumerate(combat_rooms):
            kind, act, _floor = room
            if kind != "Boss" or act != ACT_INDEX + 1:
                continue
            block = blocks[pair_index]
            entry = block["lines"][0]
            if not (entry.get("enemies") or ()):
                stats["act2_boss_no_enemies"] += 1
                continue
            if block.get("end") is None:
                stats["boss_without_combat_end"] += 1
                continue
            stats["fights"] += 1
            spec = build_spec(trace, entry, block.get("end"), rooms, index, run_seed)
            existing = specs.get(spec["spec_id"])
            if existing is None:
                specs[spec["spec_id"]] = spec
            else:
                existing["sources"].extend(spec["sources"])
                if existing["recorded_outcome"] != spec["recorded_outcome"]:
                    stats["dedupe_outcome_conflict"] += 1
    return list(specs.values()), stats


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--traces-dir", default=str(MAIN_TREE / "data"))
    parser.add_argument("--out-dir", default=str(HERE))
    parser.add_argument("--jsonl", default="act3_boss_specs.jsonl")
    parser.add_argument("--md", default="act3_boss_specs.md")
    args = parser.parse_args()

    traces_dir = Path(args.traces_dir)
    specs, stats = collect(traces_dir)
    specs.sort(key=lambda spec: (-spec["deck_size"], spec["spec_id"]))
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    jsonl = out / args.jsonl
    jsonl.write_text("".join(json.dumps(spec, ensure_ascii=False) + "\n" for spec in specs),
                     encoding="utf-8")

    usable = [s for s in specs if not s["unresolved"]]
    won = [s for s in specs if s["recorded_outcome"]["won"] is True]
    blocker = collections.Counter()
    for spec in specs:
        for item in spec["unresolved"]:
            blocker[item.split(":")[0]] += 1
    carried_enchantments = collections.Counter()
    for spec in specs:
        for pile in spec["piles"].values():
            for card in pile:
                if card["enchantment"]:
                    carried_enchantments[card["enchantment"]] += 1
    residual_power = collections.Counter()
    for spec in specs:
        for power in spec["entry_powers_residual"]:
            residual_power[f"{power['id']}+{power['amount']}"] += 1

    md = [
        "# Act 3ボス(QUEEN) 入場spec 抽出結果",
        "",
        f"- 入力: `{traces_dir}` の `*_agent.jsonl`（読み取りのみ）。戦闘 {stats['fights']} 本 →"
        f" spec {len(specs)} 件（同一 seed・floor・入場HP・デッキmultiset(付与込み)・relic・counter・"
        "potion・敵HP を1件として重複除去）。",
        f"- 除けた run: mod log 無し {stats['no_modlog']}、Act3ボス室なし {stats['no_act3_boss']}、"
        f"log と戦闘 block の突合不一致 {stats['unaligned']}。同一 spec 内で実走の勝敗が食い違った"
        f" group {stats['dedupe_outcome_conflict']} 件。",
        f"- 記録された実走: 勝 {len(won)} / 負 {len(specs) - len(won)}。"
        f"BossLab がそのまま注入できる spec（unresolved 無し）は {len(usable)} 件。",
        "",
        "## unresolved（lab がまだ再現できないもの、spec 件数）",
        "",
        "| 要因 | spec |",
        "| --- | --- |",
    ]
    for name, count in blocker.most_common():
        md.append(f"| {name} | {count} |")
    md += [
        f"| （なし） | {len(usable)} |",
        "",
        "注: enchantment は `SerializableCard.Enchantment` で復元できるので unresolved から外した"
        "（Amount は trace に出ないため、ゲーム側が使う量を表で持たせている："
        "TezcatarasEmber 1・Nimble 2・Corrupted 1・SoulsPower 1・Goopy 1・Vigorous 8。"
        "実機照合で1枚ずつ検証する）。入場時 power の多くも同じで、deck のレリックが入室時に付ける分は"
        " lab で自動再現されるので unresolved に含めていない（注入すると二重になる）。",
        "",
        "## 注入する residual power（spec 件数）",
        "",
        "| power | spec |",
        "| --- | --- |",
    ]
    for name, count in residual_power.most_common():
        md.append(f"| {name} | {count} |")
    if not residual_power:
        md.append("| （なし） | 0 |")
    md += [
        "",
        "## 復元する enchantment（札枚数）",
        "",
        "| enchantment | 札 |",
        "| --- | --- |",
    ]
    for name, count in carried_enchantments.most_common(12):
        md.append(f"| {name} | {count} |")
    md += [
        "",
        "## 入場HP帯別",
        "",
        "| 帯 | spec | 実走で勝 | 平均デッキ |",
        "| --- | --- | --- | --- |",
    ]
    for label in ("<60", "60-79", ">=80"):
        group = [s for s in specs if (s["player"]["hp"] or 0) < 60] if label == "<60" else (
            [s for s in specs if 60 <= (s["player"]["hp"] or 0) < 80] if label == "60-79" else
            [s for s in specs if (s["player"]["hp"] or 0) >= 80])
        if not group:
            continue
        md.append(f"| {label} | {len(group)} | "
                  f"{sum(1 for s in group if s['recorded_outcome']['won'] is True)} | "
                  f"{sum(s['deck_size'] for s in group) / len(group):.1f} |")
    md += [
        "",
        "生成: `python3 .dsh/extract_act3_specs.py`。"
        "計画生成: `python3 bosslab/tools/make_bosslab_plan.py --specs .dsh/act3_boss_specs.jsonl "
        "--arm base ...`。",
    ]
    md_path = out / args.md
    md_path.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {jsonl}: specs {len(specs)} usable {len(usable)} wins {len(won)} "
          f"(fights {stats['fights']}, unaligned {stats['unaligned']}, no modlog {stats['no_modlog']})")
    print("blockers:", blocker.most_common())
    print("residual powers:", residual_power.most_common())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
